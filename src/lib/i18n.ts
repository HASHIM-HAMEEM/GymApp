export function translate(language: Language, key: keyof typeof en, options?: Record<string, unknown>) {
  const value: string | undefined = (language === 'ur' ? ur[key] : undefined) ?? en[key];
  if (value === undefined) return key;
  if (!options) return value;
  return value.replace(/%\{(\w+)\}/g, (match, name: string) => {
    if (!Object.prototype.hasOwnProperty.call(options, name)) return match;
    return String(options[name]);
  });
}

